let registered = false;
export function registerPageEvents() {
  if (registered) return;
  registered = true;
  document.querySelectorAll('[data-page-action]').forEach(element => {
    const action = actions[element.dataset.pageAction];
    if (action) element.addEventListener('click', () => action(element));
  });
  document.querySelectorAll('form[data-prevent-submit]').forEach(form => form.addEventListener('submit', event => event.preventDefault()));
}
