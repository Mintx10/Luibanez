const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const { PGlite } = require('@electric-sql/pglite');
const alice = '11111111-1111-4111-8111-111111111111';
const bob = '22222222-2222-4222-8222-222222222222';
const eve = '33333333-3333-4333-8333-333333333333';

test('migration, RLS, room membership, turn authority, voting and quotas in PostgreSQL', async t => {
  const db = new PGlite();
  t.after(() => db.close());
  await db.exec(`create role anon; create role authenticated; create role service_role;
    create schema auth; create table auth.users(id uuid primary key);
    create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
    grant usage on schema auth to authenticated;
    insert into auth.users values('${alice}'),('${bob}'),('${eve}');
    create schema extensions;
    -- PGlite has no pgcrypto. Test-only substitutes exercise access/flow, never production hashing.
    create function extensions.gen_salt(text,integer) returns text language sql as $$select 'test-salt'::text$$;
    create function extensions.crypt(text,text) returns text language sql as $$select 'test-only:' || $1$$;`);
  const migration = fs.readFileSync('supabase/migrations/202611050001_secure_study.sql', 'utf8').replace('create extension if not exists pgcrypto with schema extensions;', '');
  await db.exec(migration);
  await db.exec(fs.readFileSync('supabase/migrations/202611050002_verified_games.sql', 'utf8'));
  await db.exec(fs.readFileSync('supabase/migrations/202611050003_document_sync.sql', 'utf8'));
  async function as(id, query, params = []) {
    await db.exec('reset role');
    await db.query("select set_config('request.jwt.claim.sub',$1,false)", [id]);
    await db.exec('set role authenticated');
    return db.query(query, params);
  }
  for (const id of [alice, bob, eve]) await as(id, "insert into study_profiles(id,apodo,carrera) values($1,$2,'Medicina')", [id, id === alice ? 'Alice' : 'Bob']);
  await as(alice, "insert into study_documents(id,nombre,texto) values('one','Privado','Sólo Alice')");
  assert.equal((await as(bob, 'select * from study_documents')).rows.length, 0);
  await assert.rejects(as(bob, 'insert into study_documents(user_id,id,nombre,texto) values($1,\'bad\',\'Hack\',\'No\')', [alice]), /row-level security/);
  await as(bob, 'delete from study_documents where user_id=$1', [alice]);
  assert.equal((await as(alice, 'select * from study_documents')).rows.length, 1);
  const previous=(await as(alice,"select to_jsonb(d.*) as d from study_documents d where id='one'")).rows[0].d;
  await as(bob,'select study_delete_documents($1)',[['one']]);
  assert.equal((await as(alice,"select deleted_at from study_documents where id='one'")).rows[0].deleted_at,null);
  await as(alice,'select study_delete_documents($1)',[['one']]);
  await as(alice,'select study_sync_documents($1)',[[previous]]);
  const deleted=(await as(alice,"select texto,deleted_at from study_documents where id='one'")).rows[0];
  assert.equal(deleted.texto,'');assert.ok(deleted.deleted_at);
  await as(alice, 'select study_create_room($1,$2,$3,$4,$5)', ['ABCDE', 'Sala', 'secret', true, { juego: 'bolillero', formatoModo: 'versus' }]);
  assert.match((await as(bob, 'select study_join_room($1,$2) as result', ['ABCDE', 'wrong'])).rows[0].result.error, /incorrecta/);
  assert.equal((await as(bob, 'select * from study_room_members')).rows.length, 0);
  assert.equal((await as(bob, 'select study_join_room($1,$2) as result', ['ABCDE', 'secret'])).rows[0].result.ok, true);
  assert.equal((await as(bob, 'select study_read_room($1) as result', ['ABCDE'])).rows[0].result.members.length, 2);
  async function send(id, payload) { return as(id, 'select study_send_room_event($1,$2)', ['ABCDE', payload]); }
  await assert.rejects(send(bob, { tipo: 'INICIO_PARTIDA_ONLINE' }), /anfitrión/);
  await send(bob, { tipo: 'JUGADOR_READY_STATUS', jugadorId: alice, listo: true });
  assert.equal((await as(bob, 'select ready from study_room_members where user_id=$1', [bob])).rows[0].ready, true);
  await send(alice, { tipo: 'INICIO_PARTIDA_ONLINE', jugadores: [] });
  await send(alice, { tipo: 'TURNO_INICIAR_OFICIAL', jugadorId: alice });
  await assert.rejects(send(bob, { tipo: 'FIN_EXPOSICION_ORAL', jugadorId: alice }), /No es tu turno/);
  await send(bob, { tipo: 'VOTO_EMITIDO', voto: 10, votanteId: alice });
  await assert.rejects(send(bob, { tipo: 'VOTO_EMITIDO', voto: 10 }), /duplicate key/);
  await send(alice, { tipo: 'RESULTADO_VOTACION', decision: 'paso' });
  assert.equal((await as(alice, 'select points from study_room_members where user_id=$1', [alice])).rows[0].points, 10);
  await assert.rejects(send(alice, { tipo: 'RESULTADO_VOTACION' }), /Faltan votos|duplicate/);
  assert.equal((await as(eve, 'select * from study_room_events')).rows.length, 0);
  await assert.rejects(send(eve, { tipo: 'CHAT_MSG', msg: {} }), /No pertenecés/);
  await assert.rejects(as(alice, 'update study_room_members set points=999'), /permission denied/);
  await assert.rejects(as(alice, 'select consume_ai_quota($1,$2)', [alice, 'a'.repeat(64)]), /permission denied/);
  await db.exec('reset role; set role service_role');
  for (let i = 0; i < 16; i++) assert.equal((await db.query('select consume_ai_quota($1,$2) as allowed', [alice, 'a'.repeat(64)])).rows[0].allowed, i < 15);
  // Objective games hide answer keys and validate progress, version and points atomically.
  await as(alice, 'select study_create_room($1,$2,$3,$4,$5)', ['FGHIJ','Quiz','',true,{ juego: 'bomba', formatoModo: 'versus', tiempoTurnoSegundos: 120, bomba: { maxFallos: 3 } }]);
  await as(bob, 'select study_join_room($1,$2)', ['FGHIJ','']);
  await as(bob, 'select study_send_room_event($1,$2)', ['FGHIJ',{ tipo: 'JUGADOR_READY_STATUS', listo: true }]);
  const rounds = [{ type: 'quiz', question: '2+2', options: ['1','2','3','4'], correct: 3, explanation: 'Sumá dos y dos.' }, { type: 'memory', pairs: [{ concept: 'A', definition: 'Alpha' },{ concept: 'B', definition: 'Beta' }] }];
  await assert.rejects(as(bob, 'select study_start_game($1,$2)', ['FGHIJ',rounds]), /anfitrión/);
  await assert.rejects(as(alice, 'select study_start_game($1,$2)', ['FGHIJ',[{ type: 'quiz',question:'Bad',options:['a','b','c','d'] }]]), /Pregunta inválida/);
  await as(alice, 'select study_start_game($1,$2)', ['FGHIJ',rounds]);
  const state = async id => (await as(id,'select study_game_state($1) as s',['FGHIJ'])).rows[0].s;
  const act = async (id,version,action,index) => (await as(id,'select study_game_action($1,$2,$3,$4) as s',['FGHIJ',version,action,index])).rows[0].s;
  assert.equal(JSON.stringify(await state(bob)).includes('correct'),false);
  let progress = await act(bob,0,'answer',0); assert.equal(progress.points,0); assert.equal(progress.mistakes,1);
  const stale = await act(bob,0,'answer',3); assert.equal(stale.version,1); assert.equal(stale.points,0);
  progress = await act(bob,1,'answer',3); assert.equal(progress.points,10); assert.equal(progress.type,'memory');
  assert.ok(progress.cards.every(card => card.text===''));
  await db.exec('reset role');
  const cards = (await db.query("select rounds->1->'cards' as cards from private.study_games where room_code='FGHIJ'")).rows[0].cards;
  for(const pairId of [0,1]) for(const index of cards.map((c,i)=>c.pair===pairId?i:-1).filter(i=>i>=0)) progress=await act(bob,progress.version,'flip',index);
  assert.equal(progress.complete,true); assert.equal(progress.points,30);
  assert.equal((await as(bob,'select points from study_verified_results')).rows[0].points,30);
  await act(bob,progress.version,'answer',3);
  assert.equal((await as(bob,'select * from study_verified_results')).rows.length,1);
  assert.equal((await as(alice,'select * from study_verified_results')).rows.length,0);
  await as(alice, 'select study_leave_room($1)', ['ABCDE']);
  await assert.rejects(as(bob, 'select study_read_room($1)', ['ABCDE']), /expiró/);
});
